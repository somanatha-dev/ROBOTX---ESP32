#!/usr/bin/env python3
"""Write fw_build_id.h: the firmware build identity reported in READY / DIAG SYSTEM.

    python tools/gen_fw_build_id.py            # writes ./fw_build_id.h next to the sketch
    python tools/gen_fw_build_id.py --out DIR/fw_build_id.h

Run it immediately before every build that will be flashed. comm.cpp includes the
header when it exists; without it the firmware reports "unversioned".

FW_BUILD_ID  = the 12-hex-digit source revision (`git rev-parse HEAD`), with "-dirty"
               appended when tracked files differ from it or an untracked source file
               (.ino/.cpp/.h) is present -- i.e. when the build does NOT exactly match
               that revision. "nogit" when no git revision can be read.
FW_BUILD_UTC = when this header was generated, ISO 8601 UTC.

Read-only with respect to git: only `rev-parse`, `diff --quiet` and `ls-files` are
used, none of which writes the index or the repository.
"""

import argparse
import datetime
import os
import re
import subprocess
import sys

SKETCH = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SAFE = re.compile(r"[^A-Za-z0-9._+:-]")


def git(*args):
    return subprocess.run(["git", "-C", SKETCH, *args], capture_output=True, text=True)


def build_id():
    rev = git("rev-parse", "--short=12", "HEAD")
    if rev.returncode != 0 or not rev.stdout.strip():
        return "nogit"
    ident = rev.stdout.strip()
    changed = git("diff", "--quiet", "HEAD", "--").returncode != 0
    untracked = git("ls-files", "--others", "--exclude-standard", "--",
                    "*.ino", "*.cpp", "*.h").stdout.strip()
    # The generated header itself is git-ignored, so it never makes a build dirty.
    if changed or untracked:
        ident += "-dirty"
    return ident


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(SKETCH, "fw_build_id.h"))
    args = ap.parse_args()

    ident = SAFE.sub("_", build_id())[:40]
    utc = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    text = (
        "// GENERATED by tools/gen_fw_build_id.py -- do not edit, do not commit.\n"
        "#ifndef FW_BUILD_ID_H\n#define FW_BUILD_ID_H\n"
        f'#define FW_BUILD_ID  "{ident}"\n'
        f'#define FW_BUILD_UTC "{utc}"\n'
        "#endif\n"
    )
    tmp = args.out + ".tmp"
    with open(tmp, "w", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, args.out)
    print(f"{args.out}: FW_BUILD_ID={ident} FW_BUILD_UTC={utc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
